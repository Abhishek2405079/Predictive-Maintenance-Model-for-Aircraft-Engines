def scale_frame(df):
    scaled = pd.DataFrame(
        scaler.transform(df[feature_cols]),
        columns=feature_cols,
        index=df.index,
    )
    for col in ["engine", "cycle", "RUL", "RUL_norm"]:
        if col in df.columns:
            scaled[col] = df[col].values
    return scaled

