@tf.function
def compute_saliency(batch_inputs):
    with tf.GradientTape() as tape:
        tape.watch(batch_inputs)
        preds = model(batch_inputs, training=False)
    grads = tape.gradient(preds, batch_inputs)
    return tf.abs(grads)

