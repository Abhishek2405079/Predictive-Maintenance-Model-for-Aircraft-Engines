def evaluate_split(name, y_true_norm, y_pred_norm):
    rmse_norm = np.sqrt(mean_squared_error(y_true_norm, y_pred_norm))
    mae_norm = mean_absolute_error(y_true_norm, y_pred_norm)
    return {
        "split": name,
        "rmse_norm": rmse_norm,
        "mae_norm": mae_norm,
        "rmse_cycles": rmse_norm * RUL_CAP,
        "mae_cycles": mae_norm * RUL_CAP,
    }

