def compute_train_rul(df, cap):
    out = df.copy()
    max_cycles = out.groupby("engine")["cycle"].transform("max")
    out["RUL"] = (max_cycles - out["cycle"]).clip(lower=0, upper=cap)
    out["RUL_norm"] = out["RUL"] / cap
    return out

