def create_train_sequences(df, window, stride):
    X, y, groups = [], [], []
    for engine_id, df_e in df.groupby("engine"):
        df_e = df_e.sort_values("cycle")
        values = df_e[feature_cols].to_numpy(dtype=np.float32)
        targets = df_e["RUL_norm"].to_numpy(dtype=np.float32)

        if len(values) < window:
            continue

        for start in range(0, len(values) - window + 1, stride):
            end = start + window
            X.append(values[start:end])
            y.append(targets[end - 1])
            groups.append(engine_id)

    return np.asarray(X, dtype=np.float32), np.asarray(y, dtype=np.float32), np.asarray(groups)

def create_test_windows(df, rul_values, window, cap):
    X, y = [], []
    engine_ids = sorted(df["engine"].unique())

    for idx, engine_id in enumerate(engine_ids):
        df_e = df[df["engine"] == engine_id].sort_values("cycle")
        values = df_e[feature_cols].to_numpy(dtype=np.float32)

        if len(values) >= window:
            window_values = values[-window:]
        else:
            pad = np.zeros((window - len(values), len(feature_cols)), dtype=np.float32)
            window_values = np.vstack([pad, values])

        X.append(window_values)
        y.append(np.clip(rul_values[idx], 0, cap) / cap)

    return np.asarray(X, dtype=np.float32), np.asarray(y, dtype=np.float32), engine_ids

