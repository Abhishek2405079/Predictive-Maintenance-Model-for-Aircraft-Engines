def build_tflite_safe_model(input_shape):
    return models.Sequential([
        layers.Input(shape=input_shape, dtype=tf.float32),
        layers.RNN(
            layers.LSTMCell(128),
            return_sequences=True,
            unroll=True
        ),
        layers.Dropout(0.25),
        layers.RNN(
            layers.LSTMCell(64),
            unroll=True
        ),
        layers.Dense(64, activation="relu"),
        layers.Dropout(0.2),
        layers.Dense(1, dtype="float32"),
    ])

